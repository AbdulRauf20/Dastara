"use server";

import { createAdminClient } from "@/lib/supabase/admin";
import { orderInquirySchema } from "@/lib/validation/order";
import { ok, fail, zodFieldErrors, type ActionResult } from "@/lib/action-result";
import { rateLimit, getClientIp, hashIp } from "@/lib/rate-limit";
import { computeOrderTotals } from "@/lib/pricing";
import { buildOrderMessage, buildWaUrl } from "@/lib/whatsapp";
import { normalizePkPhone } from "@/lib/phone";
import { availabilityMeta, type Availability } from "@/lib/constants";
import { getSiteSettings, resolveWhatsappNumber } from "@/services/site";
import { primaryImage } from "@/services/catalog";

export interface OrderActionData {
  orderRef: string;
  waUrl: string;
}

/**
 * Create a guest order inquiry.
 *
 * Security/business guarantees:
 *  - Rate limited per IP + honeypot.
 *  - All inputs validated server-side with Zod.
 *  - Availability is re-checked and price is read from the DB — the browser's
 *    price is never trusted.
 *  - The inquiry + snapshots are persisted BEFORE any redirect. The WhatsApp
 *    URL is returned only after a successful DB write.
 */
export async function createOrderInquiry(
  _prev: ActionResult<OrderActionData> | null,
  formData: FormData,
): Promise<ActionResult<OrderActionData>> {
  // 1. Rate limit
  const ip = await getClientIp();
  const limit = rateLimit(`order:${ip}`, 5, 60_000);
  if (!limit.ok) {
    return fail("Too many requests. Please wait a moment and try again.");
  }

  // 2. Validate
  const parsed = orderInquirySchema.safeParse({
    productId: formData.get("productId"),
    quantity: formData.get("quantity"),
    fullName: formData.get("fullName"),
    phone: formData.get("phone"),
    city: formData.get("city"),
    deliveryAddress: formData.get("deliveryAddress"),
    preferredVariant: formData.get("preferredVariant") ?? "",
    specialInstructions: formData.get("specialInstructions") ?? "",
    giftMessage: formData.get("giftMessage") ?? "",
    website: formData.get("website") ?? "",
  });

  if (!parsed.success) {
    return fail("Please check the form and try again.", zodFieldErrors(parsed.error.flatten()));
  }
  const input = parsed.data;

  // Honeypot tripped — pretend success without writing.
  if (input.website) {
    return fail("Something went wrong. Please try again.");
  }

  const phone = normalizePkPhone(input.phone);
  if (!phone) return fail("Enter a valid Pakistani mobile number.");

  const supabase = createAdminClient();

  try {
    // 3. Re-fetch product authoritatively.
    const { data: product, error: productErr } = await supabase
      .from("products")
      .select("id, name, sku, price_paisa, availability, is_published")
      .eq("id", input.productId)
      .maybeSingle();

    if (productErr) throw productErr;
    if (!product || !product.is_published) {
      return fail("This product is no longer available.");
    }

    const meta = availabilityMeta[product.availability as Availability];
    if (!meta || !meta.canOrder) {
      return fail(`This product cannot be ordered right now (${meta?.label ?? "unavailable"}).`);
    }

    // 4. Compute totals from DB price + store settings.
    const settings = await getSiteSettings();
    const totals = computeOrderTotals({
      unitPricePaisa: product.price_paisa,
      quantity: input.quantity,
      deliveryFeePaisa: settings.delivery_fee_paisa,
      freeDeliveryThresholdPaisa: settings.free_delivery_threshold_paisa,
    });

    // 5. Upsert customer by phone.
    const { data: customer } = await supabase
      .from("customers")
      .upsert(
        {
          full_name: input.fullName,
          phone,
          phone_raw: input.phone,
          city: input.city,
        },
        { onConflict: "phone" },
      )
      .select("id")
      .single();

    // 6. Insert inquiry (order_ref generated by DB trigger).
    const { data: inquiry, error: inquiryErr } = await supabase
      .from("order_inquiries")
      .insert({
        customer_id: customer?.id ?? null,
        customer_name: input.fullName,
        customer_phone: phone,
        city: input.city,
        delivery_address: input.deliveryAddress,
        preferred_variant: input.preferredVariant || null,
        special_instructions: input.specialInstructions || null,
        gift_message: input.giftMessage || null,
        subtotal_paisa: totals.subtotalPaisa,
        delivery_fee_paisa: totals.deliveryFeePaisa,
        total_paisa: totals.totalPaisa,
        status: "inquiry_received",
        payment_status: "not_requested",
        source: "storefront",
        ip_hash: hashIp(ip),
      })
      .select("id, order_ref")
      .single();

    if (inquiryErr || !inquiry) throw inquiryErr ?? new Error("Insert failed");

    // 7. Snapshot the ordered item (primary image resolved separately).
    const { data: images } = await supabase
      .from("product_images")
      .select("storage_path, is_primary, display_order")
      .eq("product_id", product.id);
    const img = primaryImage(images ?? []);
    const { error: itemErr } = await supabase.from("order_items").insert({
      inquiry_id: inquiry.id,
      product_id: product.id,
      product_name: product.name,
      product_sku: product.sku,
      unit_price_paisa: totals.unitPricePaisa,
      quantity: totals.quantity,
      line_total_paisa: totals.subtotalPaisa,
      image_path: img?.storage_path ?? null,
    });
    if (itemErr) throw itemErr;

    // 8. Initial status history entry.
    await supabase.from("order_status_history").insert({
      inquiry_id: inquiry.id,
      from_status: null,
      to_status: "inquiry_received",
      note: "Inquiry submitted by customer via storefront.",
    });

    // 9. Bump the product's inquiry counter (for honest analytics).
    await supabase
      .rpc("increment_product_inquiry", { p_product_id: product.id })
      .then(() => undefined, () => undefined);

    // 10. Build the WhatsApp message from the SAVED inquiry data.
    const message = buildOrderMessage({
      orderRef: inquiry.order_ref,
      productSku: product.sku,
      productName: product.name,
      quantity: totals.quantity,
      unitPricePaisa: totals.unitPricePaisa,
      subtotalPaisa: totals.subtotalPaisa,
      deliveryFeePaisa: totals.deliveryFeePaisa,
      totalPaisa: totals.totalPaisa,
      customerName: input.fullName,
      city: input.city,
      deliveryAddress: input.deliveryAddress,
      preferredVariant: input.preferredVariant,
      specialInstructions: input.specialInstructions,
      giftMessage: input.giftMessage,
    });
    const waUrl = buildWaUrl(resolveWhatsappNumber(settings), message);

    return ok(
      { orderRef: inquiry.order_ref, waUrl },
      "Your inquiry has been recorded.",
    );
  } catch (err) {
    console.error("[order] failed to create inquiry", err);
    return fail("We couldn't save your inquiry. Please try again.");
  }
}
